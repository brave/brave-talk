import { act, createElement, useEffect } from "react";
import { createRoot, Root } from "react-dom/client";
import { fetchJWT } from "../rooms";
import { useCallSetupStatus } from "./use-call-setup-status";
import { subscriptionCheckWithTimeout } from "./use-subscribed-status";

jest.mock("../rooms", () => ({ fetchJWT: jest.fn() }));
jest.mock("./use-subscribed-status", () => ({
  subscriptionCheckWithTimeout: jest.fn(),
}));

const mockFetchJWT = fetchJWT as jest.MockedFunction<typeof fetchJWT>;
const mockSubscriptionCheck =
  subscriptionCheckWithTimeout as jest.MockedFunction<
    typeof subscriptionCheckWithTimeout
  >;

// e.g. as generated by the `/talk` slack extension
const ROOM_NAME = "abcdefghijklmnopqrstuvwxyz0123456789-_ABCDE";

let setup: ReturnType<typeof useCallSetupStatus>;
let root: Root;

interface HarnessProps {
  isCreate: boolean;
  onRender: (callSetup: ReturnType<typeof useCallSetupStatus>) => void;
}

const Harness = ({ isCreate, onRender }: HarnessProps) => {
  const callSetup = useCallSetupStatus(isCreate);
  useEffect(() => onRender(callSetup));
  return null;
};

const render = async (isCreate: boolean) => {
  root = createRoot(document.createElement("div"));
  await act(async () => {
    root.render(
      createElement(Harness, {
        isCreate,
        onRender: (callSetup) => {
          setup = callSetup;
        },
      }),
    );
  });
};

const advanceTime = async (ms: number) => {
  await act(async () => {
    await jest.advanceTimersByTimeAsync(ms);
  });
};

beforeAll(() => {
  (globalThis as any).IS_REACT_ACT_ENVIRONMENT = true;
});

beforeEach(() => {
  jest.useFakeTimers();
  jest.spyOn(console, "log").mockImplementation(() => {});

  window.history.replaceState(null, "", `/${ROOM_NAME}?create=y`);

  // the room doesn't exist until someone creates it, and we're not a subscriber
  mockFetchJWT.mockImplementation(async (roomName, createP) => {
    if (!createP) {
      throw new Error("The room does not exist");
    }
    return { jwt: `jwt-for-${roomName}` };
  });
  mockSubscriptionCheck.mockResolvedValue(false);
});

afterEach(() => {
  act(() => root.unmount());
  jest.useRealTimers();
  jest.restoreAllMocks();
  mockFetchJWT.mockReset();
  mockSubscriptionCheck.mockReset();
});

test("with create=y a non-subscriber waits for a subscriber to create the room", async () => {
  await render(true);

  expect(setup.notice).toBe("Waiting for a subscriber to create the room...");
  expect(setup.isCallReady).toBe(false);
  expect(setup.hasInitialRoom).toBe(false);
  expect(mockFetchJWT).toHaveBeenCalledTimes(1);

  // ...and keeps checking whether they have done so
  await advanceTime(5_000);
  expect(mockFetchJWT).toHaveBeenCalledTimes(2);
  expect(mockFetchJWT).not.toHaveBeenCalledWith(
    expect.anything(),
    true,
    expect.anything(),
  );
  expect(setup.isCallReady).toBe(false);
});

test("starting a free call whilst waiting for a subscriber creates the requested room", async () => {
  await render(true);
  expect(setup.notice).toBe("Waiting for a subscriber to create the room...");

  await act(async () => setup.onStartCall());

  expect(mockFetchJWT).toHaveBeenLastCalledWith(
    ROOM_NAME,
    true,
    expect.any(Function),
  );
  expect(setup.roomName).toBe(ROOM_NAME);
  expect(setup.jwt).toBe(`jwt-for-${ROOM_NAME}`);
  expect(setup.isCallReady).toBe(true);

  // and we've stopped polling for a subscriber to create it
  const calls = mockFetchJWT.mock.calls.length;
  await advanceTime(15_000);
  expect(mockFetchJWT).toHaveBeenCalledTimes(calls);
});

test("starting a call otherwise creates a new room", async () => {
  window.history.replaceState(null, "", "/");
  await render(false);
  expect(setup.roomName).toBeUndefined();

  await act(async () => setup.onStartCall());

  expect(setup.roomName).toMatch(/^[A-Za-z0-9-_]{43}$/);
  expect(setup.roomName).not.toBe(ROOM_NAME);
  expect(setup.jwt).toBe(`jwt-for-${setup.roomName}`);
  expect(mockFetchJWT).toHaveBeenLastCalledWith(
    setup.roomName,
    true,
    expect.any(Function),
  );
});
